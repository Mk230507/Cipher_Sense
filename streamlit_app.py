"""Streamlit presentation layer for CipherSense AI."""

from __future__ import annotations

import json
from pathlib import Path

import streamlit as st

from ciphersense.classifier import load_dataset, predict, train_models
from ciphersense.crypto import CryptoError, decrypt_message, encrypt_message
from ciphersense.explainability import classical_features
from ciphersense.privacy import PrivacyAnalyzer

st.set_page_config(page_title="CipherSense AI", page_icon="🛡️", layout="wide")
st.title("🛡️ CipherSense AI")
st.caption("Local secure messaging, privacy analysis, and text-risk decision support")

@st.cache_resource
def resources():
    texts, labels = load_dataset()
    return train_models(texts, labels), PrivacyAnalyzer()


models, analyzer = resources()
page = st.sidebar.radio("Workspace", ["Dashboard", "Secure messaging", "Privacy analysis", "Threat detection", "Model laboratory", "About"])

if page == "Dashboard":
    st.header("Security and intelligence dashboard")
    st.info("All plaintext analysis is local by default. Classifier outputs are decision support, not proof of malicious intent.")
    c1, c2, c3 = st.columns(3)
    c1.metric("Encryption", "AES-256-GCM")
    c2.metric("Key derivation", "Scrypt")
    c3.metric("NLP mode", analyzer.model_status)
    st.markdown("Use the sidebar to encrypt messages, review sensitive entities, classify text, and inspect measured model artifacts.")
elif page == "Secure messaging":
    st.header("Secure messaging")
    message = st.text_area("Message or JSON payload", height=240)
    password = st.text_input("Password", type="password")
    c1, c2 = st.columns(2)
    if c1.button("Encrypt"):
        try:
            st.code(encrypt_message(message, password), language="json")
        except CryptoError as exc:
            st.error(str(exc))
    if c2.button("Decrypt"):
        try:
            st.text_area("Decrypted message", decrypt_message(message, password), height=180)
        except CryptoError:
            st.error("Unable to decrypt: the password may be wrong or the payload may be damaged.")
elif page == "Privacy analysis":
    st.header("Local NLP privacy analysis")
    text = st.text_area("Text to inspect", height=220)
    if st.button("Analyze"):
        entities = analyzer.analyze(text)
        if entities:
            st.dataframe([entity.__dict__ for entity in entities], use_container_width=True)
            st.text_area("Redacted preview", analyzer.redact(text, entities), height=150)
        else:
            st.success("No supported sensitive entities detected.")
    st.caption(analyzer.model_status)
elif page == "Threat detection":
    st.header("Spam and phishing decision support")
    text = st.text_area("Message to classify", height=220)
    model_name = st.selectbox("Model", list(models))
    if st.button("Classify"):
        result = predict(models[model_name], text)
        st.metric("Predicted class", result.label)
        st.write(f"**{result.score_kind}:** {result.score:.3f}")
        st.warning(result.warning)
        features = classical_features(models[model_name], text)
        if features:
            st.dataframe([{"feature": term, "contribution": value} for term, value in features])
elif page == "Model laboratory":
    st.header("Measured experiment artifacts")
    metrics_path = Path("artifacts/classical_metrics.json")
    if metrics_path.exists():
        data = json.loads(metrics_path.read_text(encoding="utf-8"))
        st.dataframe([{"model": name, "macro_f1": result["macro_f1"]} for name, result in data.items()])
        st.caption("Metrics are generated by train_classical.py; the bundled corpus is a smoke-test corpus.")
    else:
        st.info("Run train_classical.py to generate measured metrics.")
elif page == "About":
    st.header("About CipherSense AI")
    st.write("A modular university project demonstrating authenticated encryption, local NLP privacy review, classical text classification, and optional transformer fine-tuning.")
    st.write("See README.md for provenance, limitations, reproducibility steps, and the distinction between encoding and encryption.")
